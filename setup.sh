setup_xfs_symlinks() {
  local xfsroot="/xfs"
  local xfshome="/xfs/$USER"
  local it

  if [[ "$OSTYPE" == darwin* ]]; then
    return 0
  fi

  if ! [[ -d "$xfshome" ]]; then
    if [[ $UID != 0 && -d "$xfsroot" ]] && mountpoint "$xfsroot" >/dev/null 2>&1; then
      mkdir -m 0750 "$xfshome" >/dev/null 2>&1 || true
    fi
    if ! [[ -d "$xfshome" ]]; then
      # Remove possible dead symlinks, unless it seems like xfs isn't mounted
      for it in ~/.local/share/{containers,flatpak} ~/.cache; do
        if [[ -L "$it" && ! -d "$it" ]]; then
          if [[ "$(readlink "$it")" == $xfsroot/* ]] && fgrep " $xfsroot " /etc/fstab >/dev/null 2>&1; then
            continue
          fi
          rm -f "$it"
        fi
      done
      return 0
    fi
  fi

  if [[ $UID == 0 || $USER == nobody || ! -d "/home/$USER" ]]; then
    return 0
  fi

  if ! [[ -d ~/.local/share ]]; then
    mkdir -p -m 0700 ~/.local ~/.local/share
  fi

  for it in \
      "$xfshome/cache=$HOME/.cache" \
      "$xfshome/containers=$HOME/.local/share/containers" \
      "$xfshome/flatpak=$HOME/.local/share/flatpak"; do
    local src="${it#*=}"
    local target="${it%=*}"
    if ! [[ -d "$target" ]]; then
      mkdir -m 0750 "$target" || true
      if ! [[ -d "$target" ]]; then
        continue
      fi
    fi
    if [[ -d "$src" ]]; then
      continue
    fi
    if [[ -L "$src" ]]; then
      rm -f "$src" || true
    fi
    ln -sf "$target" "$src"
    echo "Symlinked $src -> $target"
  done
}
